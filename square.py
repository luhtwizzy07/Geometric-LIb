def area(a):
    '''
    Описание:
        Принимает число a, возвращает площадь квадрата со стороной a
        
    Пример вызова:
        >>> area(10)
        100
    '''
    return a * a

def perimeter(a):
    '''
    Описание:
        Принимает число a, возвращает периметр квадрата со стороной a
        
    Пример вызова:
        >>> perimeter(10)
        40
    '''
    return 4 * a