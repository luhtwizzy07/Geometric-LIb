def area(a, b):
    '''
    Описание:
        Принимает 2 числа a и b, возвращает площадь прямоугольника со сторонами a и b
        
    Пример вызова:
        >>> area(3.41, 14)
        47.74
    ''' 
    return a * b 

def perimeter(a, b):
    '''
    Описание:
        Принимает 2 числа a и b, возвращает периметр прямоугольника со сторонами a и b
        
    Пример вызова:
        >>> perimeter(3.41, 14)
        34.82
    ''' 
    return 2 * (a + b)